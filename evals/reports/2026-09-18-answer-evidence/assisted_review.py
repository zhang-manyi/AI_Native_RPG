def main():
    rows = []
    for run, decisions in REVIEWS.items():
        report = json.loads((ROOT / run / "report.json").read_text(encoding="utf-8"))
        assert len(decisions) == len(report["rows"])
        for row, values in zip(report["rows"], decisions, strict=True):
            if "dialogue" not in row:
                assert values is None
                continue
            a, u, d, f, r, e, reason = values
            label = {
                "id": row["id"],
                "review_source": "Codex assistant review",
                "dialogue_sha256": hashlib.sha256(row["dialogue"].encode()).hexdigest(),
                "answer_correct": a,
                "unsupported": u,
                "disclosure": d,
                "false_success": f,
                "refusal_appropriate": r,
                "expression_consistent": e,
                "reason": reason,
            }
            rows.append(label)
    with (ROOT / "review_labels.json").open("x", encoding="utf-8") as stream:
        json.dump(
            {"review_source": "Codex assistant review", "runs": list(REVIEWS), "rows": rows},
            stream,
            ensure_ascii=False,
            indent=2,
        )


if __name__ == "__main__":
    main()
